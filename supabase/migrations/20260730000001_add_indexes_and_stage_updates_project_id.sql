




CREATE TABLE IF NOT EXISTS public.projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id UUID,
    marketing_id UUID,
    engineer_id UUID,
    status TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.project_stages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT REFERENCES public.projects(id) ON DELETE CASCADE,
    sequence INT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.stage_updates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stage_id BIGINT REFERENCES public.project_stages(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.project_files (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT REFERENCES public.projects(id) ON DELETE CASCADE,
    stage_id BIGINT REFERENCES public.project_stages(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID,
    target_role TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);


ALTER TABLE public.stage_updates
  ADD COLUMN IF NOT EXISTS project_id BIGINT REFERENCES public.projects(id) ON DELETE CASCADE;


CREATE OR REPLACE FUNCTION public.sync_stage_updates_project_id()
RETURNS TRIGGER AS $$
BEGIN
  IF NEW.stage_id IS NOT NULL THEN
    SELECT project_id INTO NEW.project_id
    FROM public.project_stages
    WHERE id = NEW.stage_id;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS trg_sync_stage_updates_project_id ON public.stage_updates;
CREATE TRIGGER trg_sync_stage_updates_project_id
  BEFORE INSERT OR UPDATE ON public.stage_updates
  FOR EACH ROW
  EXECUTE FUNCTION public.sync_stage_updates_project_id();


UPDATE public.stage_updates su
SET project_id = ps.project_id
FROM public.project_stages ps
WHERE su.stage_id = ps.id
  AND su.project_id IS NULL;


DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'uq_project_stages_project_sequence'
  ) THEN
    ALTER TABLE public.project_stages
      ADD CONSTRAINT uq_project_stages_project_sequence UNIQUE (project_id, sequence);
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_project_stages_project_seq ON public.project_stages(project_id, sequence);


CREATE INDEX IF NOT EXISTS idx_projects_client_created ON public.projects(client_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_projects_marketing_created ON public.projects(marketing_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_projects_engineer_created ON public.projects(engineer_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_projects_status_created ON public.projects(status, created_at DESC);


CREATE INDEX IF NOT EXISTS idx_stage_updates_stage_created ON public.stage_updates(stage_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_stage_updates_project_created ON public.stage_updates(project_id, created_at DESC);


CREATE INDEX IF NOT EXISTS idx_project_files_project_created ON public.project_files(project_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_project_files_stage_created ON public.project_files(stage_id, created_at DESC);


CREATE INDEX IF NOT EXISTS idx_notifications_user_created ON public.notifications(user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_notifications_role_created ON public.notifications(target_role, created_at DESC);