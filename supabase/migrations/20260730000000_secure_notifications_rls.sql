



CREATE TABLE IF NOT EXISTS public.users (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    role TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID REFERENCES public.users(id) ON DELETE CASCADE,
    target_role TEXT,
    title TEXT,
    message TEXT,
    is_read BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);


ALTER TABLE public.notifications ENABLE ROW LEVEL SECURITY;


DROP POLICY IF EXISTS "notifications_insert_policy" ON public.notifications;
DROP POLICY IF EXISTS "notifications_select_policy" ON public.notifications;
DROP POLICY IF EXISTS "notifications_update_policy" ON public.notifications;
DROP POLICY IF EXISTS "notifications_delete_policy" ON public.notifications;
DROP POLICY IF EXISTS "Allow select for owner or target role" ON public.notifications;
DROP POLICY IF EXISTS "Allow update for owner or target role" ON public.notifications;
DROP POLICY IF EXISTS "Allow delete for owner" ON public.notifications;
DROP POLICY IF EXISTS "Allow delete for owner or target role" ON public.notifications;


CREATE POLICY "Allow select for owner or target role" ON public.notifications
  FOR SELECT TO authenticated
  USING (
    user_id = auth.uid()
    OR (
      target_role IS NOT NULL
      AND target_role = (SELECT role FROM public.users WHERE id = auth.uid())
    )
  );


CREATE POLICY "Allow update for owner or target role" ON public.notifications
  FOR UPDATE TO authenticated
  USING (
    user_id = auth.uid()
    OR (
      target_role IS NOT NULL
      AND target_role = (SELECT role FROM public.users WHERE id = auth.uid())
    )
  )
  WITH CHECK (
    user_id = auth.uid()
    OR (
      target_role IS NOT NULL
      AND target_role = (SELECT role FROM public.users WHERE id = auth.uid())
    )
  );


CREATE POLICY "Allow delete for owner or target role" ON public.notifications
  FOR DELETE TO authenticated
  USING (
    user_id = auth.uid()
    OR (
      target_role IS NOT NULL
      AND target_role = (SELECT role FROM public.users WHERE id = auth.uid())
    )
  );