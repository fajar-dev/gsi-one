



CREATE TABLE IF NOT EXISTS public.bookings (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name       VARCHAR(255) NOT NULL,
    company_name    VARCHAR(255),
    email           VARCHAR(255) NOT NULL,
    phone           VARCHAR(50)  NOT NULL,
    service_type    VARCHAR(255) NOT NULL,
    location        TEXT         NOT NULL,
    
    
    
    
    
    preferred_date  DATE,
    message         TEXT,
    status          VARCHAR(50)  NOT NULL DEFAULT 'pending'
                    CHECK (status IN ('pending', 'claimed', 'approved', 'rejected')),
    claimed_by      VARCHAR(255),
    claimed_at      TIMESTAMPTZ,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT TIMEZONE('utc'::text, NOW())
);


CREATE INDEX IF NOT EXISTS idx_bookings_created_at ON public.bookings (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_bookings_status ON public.bookings (status);


ALTER TABLE public.bookings ENABLE ROW LEVEL SECURITY;


DROP POLICY IF EXISTS "bookings_insert_public" ON public.bookings;
CREATE POLICY "bookings_insert_public" ON public.bookings
    FOR INSERT TO anon, authenticated
    WITH CHECK (true);

DROP POLICY IF EXISTS "bookings_select_staff" ON public.bookings;
CREATE POLICY "bookings_select_staff" ON public.bookings
    FOR SELECT TO authenticated
    USING (
        EXISTS (
            SELECT 1 FROM public.users
            WHERE users.id = auth.uid()
              AND users.role IN ('admin', 'marketing', 'engineer')
        )
    );


DROP POLICY IF EXISTS "bookings_update_staff" ON public.bookings;
CREATE POLICY "bookings_update_staff" ON public.bookings
    FOR UPDATE TO authenticated
    USING (
        EXISTS (
            SELECT 1 FROM public.users
            WHERE users.id = auth.uid()
              AND users.role IN ('admin', 'marketing', 'engineer')
        )
    )
    WITH CHECK (
        EXISTS (
            SELECT 1 FROM public.users
            WHERE users.id = auth.uid()
              AND users.role IN ('admin', 'marketing', 'engineer')
        )
    );

DROP POLICY IF EXISTS "bookings_delete_admin" ON public.bookings;
CREATE POLICY "bookings_delete_admin" ON public.bookings
    FOR DELETE TO authenticated
    USING (
        EXISTS (
            SELECT 1 FROM public.users
            WHERE users.id = auth.uid()
              AND users.role = 'admin'
        )
    );


