




CREATE TABLE IF NOT EXISTS public.projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE public.projects 
  ADD COLUMN IF NOT EXISTS project_code TEXT,
  ADD COLUMN IF NOT EXISTS client_id UUID,
  ADD COLUMN IF NOT EXISTS created_by UUID;




INSERT INTO storage.buckets (id, name, public)
VALUES ('projects', 'projects', false)
ON CONFLICT (id) DO UPDATE SET public = false;


DROP POLICY IF EXISTS "Allow authenticated select project files" ON storage.objects;
DROP POLICY IF EXISTS "Allow staff upload project files" ON storage.objects;


CREATE POLICY "Allow authenticated select project files" ON storage.objects
  FOR SELECT TO authenticated
  USING (
    bucket_id = 'projects'
    AND (
      EXISTS (SELECT 1 FROM public.users WHERE id = auth.uid() AND role IN ('admin', 'marketing', 'engineer'))
      OR EXISTS (
        SELECT 1 FROM public.projects p
        WHERE (p.id::text = (storage.foldername(name))[1] OR p.project_code = (storage.foldername(name))[1])
        AND (p.client_id = auth.uid() OR p.created_by = auth.uid())
      )
    )
  );


CREATE POLICY "Allow staff upload project files" ON storage.objects
  FOR INSERT TO authenticated
  WITH CHECK (
    bucket_id = 'projects'
    AND EXISTS (
      SELECT 1 FROM public.users WHERE id = auth.uid() AND role IN ('admin', 'marketing', 'engineer')
    )
  );